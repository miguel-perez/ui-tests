// README text is the same content model as the two routes. Preserve contributing verbatim.
import { readFile, writeFile } from 'node:fs/promises'
import * as copy from '../lib/copy.ts'
import { capture, surfaces } from './render-terminal.mjs'
import { stripVTControlCharacters } from 'node:util'

const original = await readFile('README.md', 'utf8')
const start = original.indexOf('## Contributing and automation')
if (start < 0) throw new Error('README contributing section not found')
const contributing = original.slice(start)
function text(value) {
  if (typeof value === 'string') return [value]
  return Object.values(value).flatMap(text)
}
const blocks = [`# ui-tests\n\n${copy.promise}\n\n${copy.intro}`]
for (const [title, values] of Object.entries({ 'The promise and the run': copy.landing, 'Agent runs': copy.agent, 'Without a repository': copy.hosted, 'The file': copy.inviteExample, 'The problems': copy.problems, 'Where the people come from': copy.sources, 'This page runs this test': copy.example, 'Getting started': copy.guide, 'Commands': copy.commands, 'Site navigation and controls': copy.ui, 'Rehearsal': copy.rehearsal })) {
  blocks.push(`## ${title}\n\n` + text(values).map(value => value.startsWith('import ') ? `\`\`\`ts\n${value}\n\`\`\`` : value.startsWith('<') ? `\`\`\`html\n${value}\n\`\`\`` : value).join('\n\n'))
}
blocks.push('## Terminal output\n\nThese frames are generated by the CLI’s Ink renderer.')
for (const name of ['report', 'agent', 'commands', 'init', 'dev', 'run']) {
  const { frame } = await capture(surfaces[name])
  blocks.push(`### ${name}\n\n\`\`\`text\n${stripVTControlCharacters(frame)}\n\`\`\``)
}
await writeFile('README.md', blocks.join('\n\n') + '\n\n' + contributing)
